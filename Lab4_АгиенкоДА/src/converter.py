"""Класс Converter — преобразование вещественного числа по диапазонам.

Срез знаний по юнит-тестам (ЛР4, PTPM-VKI).
"""


class Converter:
    """Преобразует вещественное число (точность 1 знак) в целое по правилам."""

    @staticmethod
    def do(x: float) -> int:
        """Вернуть целое число по диапазону входного значения x.

        x >= 100.7          -> 1000
        0 < x < 100.7       -> int(x)            (отбрасывание дробной части)
        x == 0.0            -> ValueError
        -30.4 <= x < 0      -> int(x) - 5
        x <= -30.5          -> -2000
        """
        if x >= 100.7:
            return 1000
        if x > 0:
            return int(x)
        if x == 0.0:
            raise ValueError("x не может быть равен 0.0")
        if x >= -30.4:
            return int(x) - 5
        return -2000
